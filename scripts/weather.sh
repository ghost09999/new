#!/bin/bash

# Проверяем, установлен ли curl (нужен для запроса)
if ! command -v curl &> /dev/null; then
    echo "Ошибка: curl не установлен. Установи: sudo apt install curl"
    exit 1
fi

echo "=== ПОГОДА В АЛМАТЫ ==="
# Запрос к wttr.in с параметрами:
# 0 - только текущая погода (без прогноза на 3 дня)
# T - без цветовых кодов (чтобы нормально читалось)
# n - с названием локации
curl -s "wttr.in/Almaty?0Tn"

echo ""
echo "=== ГОТОВО ==="
